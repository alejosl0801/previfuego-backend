var _PF_IDX_CODIGO = null;
var _PF_IDX_NOMBRE = null;

function pfBuildIndex() {
  _PF_IDX_CODIGO = {};
  _PF_IDX_NOMBRE = {};
  for (var i = 0; i < PF_CLIENTES.length; i++) {
    var c = PF_CLIENTES[i];
    if (c.codigo) _PF_IDX_CODIGO[c.codigo.toUpperCase()] = c;
    _PF_IDX_NOMBRE[c.nombre.toUpperCase()] = c;
  }
}
